# -*- coding: utf-8 -*-
"""
Генерация Word-документа «Карта данных»:
какие данные берём из каждого листа исходного Excel,
куда они попадают в PostgreSQL и где используются в расчётах.

Результат: output/Карта_данных.docx
Запуск:  python 04_reports/data_lineage_doc.py
"""

import os
import sys

from docx import Document
from docx.shared import Pt

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config


def h(doc, text, level=1):
    doc.add_heading(text, level=level)


def p(doc, text):
    return doc.add_paragraph(text)


def bullets(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def table(doc, header, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    t.autofit = True
    for j, htext in enumerate(header):
        t.rows[0].cells[j].text = htext
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            t.rows[i + 1].cells[j].text = str(val)
    return t


def main():
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(10)

    h(doc, "Карта данных проекта", 0)
    p(doc, "Источник: «Отчёт_Пульс_Продаж_Новостроек_Москва_2025.11.xlsx». "
           "Документ описывает, какие данные берём из каждого листа, "
           "куда они сохраняются и где используются в расчётах.")

    h(doc, "1. Общая схема потоков данных")
    bullets(doc, [
        "Excel (2 листа) -> data/raw_deals.csv + data/zhk.csv "
        "(шаг 1, load_files.py)",
        "raw_deals.csv -> очистка -> data/clean_deals.csv "
        "+ новые колонки: цена, цена_квм, источник_цены (шаг 2, cleaning.py)",
        "clean_deals.csv + zhk.csv -> JOIN по ID Корпуса -> признаки "
        "months_to_vve, стадия_сдачи, deal_year/deal_month (шаг 3, analysis.py)",
        "-> метрики output/metrics.json, графики, report.pdf, report.xlsx "
        "(шаг 4, reports.py)",
        "-> PostgreSQL real_estate_db: таблицы deals, zhk, analysis_results "
        "(шаг 5, save_results.py)",
        "REST API open.er-api.com -> data/usd_rate.csv (курс USD/RUB)",
        "PostgreSQL <- читаем SQL-запросами (load_database.py) и "
        "через API-сервер /metrics (api_server.py)",
    ])

    h(doc, "2. Листы исходного Excel: что берём и почему")
    table(doc,
          ["Лист Excel", "Используем?", "Что это / почему"],
          [
              ["Данные по лотам из выписок", "ДА, основной",
               "607 053 реальных сделок ДДУ за 2014-2025. Из 40 колонок "
               "берём 18 (см. раздел 3)"],
              ["Справочник по ЖК", "ДА, справочник",
               "2 188 корпусов ЖК: стадия строительства, сроки ВВЭ, МКАД, "
               "этажность и др. Берём 20 колонок (раздел 4). "
               "JOIN к сделкам по ID Корпуса"],
              ["Прайс-лист", "нет",
               "Текущие цены на лоты в продаже. Не нужен: цена прайс-листа "
               "на момент продажи уже есть в самой таблице сделок"],
              ["Динамика стадий", "нет",
               "Помесячная агрегация стадий продаж. У нас есть реальные даты "
               "сделок - строим свой ряд точнее"],
              ["Готовый отчёт", "нет", "Готовые агрегации автора файла - "
               "мы строим свой анализ"],
              ["Стадии продаж", "нет", "Справочный лист стадий"],
              ["Выборка ЖК", "нет", "Подборка ЖК для готового отчёта"],
              ["Цикл проектов", "нет", "Справочные данные о циклах проектов"],
              ["Инструкция", "нет", "Описание структуры файла"],
              ["Нельзя измерить", "нет", "Служебный лист"],
          ])

    h(doc, "3. Лист «Данные по лотам из выписок» -> таблица deals")
    p(doc, "607 053 строки -> после очистки 547 324 строки. "
           "Каждая колонка:")
    table(doc,
          ["Колонка в Excel", "Очистка", "В БД deals", "Где в расчётах"],
          [
              ["ID ЖК", "-", "id_zhk", "JOIN со справочником (SQL)"],
              ["ID Корпуса", "-", "id_korpus", "JOIN со справочником "
               "(точный ключ merge в pandas)"],
              ["Регион", "-", "-", "признак ML (категория)"],
              ["Название ЖК", "-", "zhk_name", "заполнение комнат модой "
               "по ЖК; признак регрессии"],
              ["Девелопер", "-", "developer", "признак ML"],
              ["Класс ЖК", "-", "housing_class", "важнейший признак "
               "регрессии (43%); отчёты по классам"],
              ["Административный округ/ Район", "-> Район", "district",
               "признак ML; SQL-отчёт по районам"],
              ["Дата договора", "строка -> дата", "deal_date",
               "временной ряд и прогноз 2026; deal_year/deal_month; "
               "months_to_vve"],
              ["Регистрационный номер ДДУ", "-", "-",
               "дедупликация: удалено 58 569 повторов"],
              ["Стоимость по ДДУ, руб.", "приоритет цены", "-> price",
               "целевая цена сделки (источник «ДДУ»)"],
              ["Стоимость объекта по прайс-листу", "x 0,964 -> цена",
               "-> price", "цена, если ДДУ нет (источник «прайс-лист»)"],
              ["Площадь", "-", "area", "цена_квм = цена/площадь; "
               "признак ML"],
              ["Комнат", "студия -> 0, пропуски - мода по ЖК", "rooms",
               "признак ML (категория, а не число)"],
              ["Этаж", "пропуски - медиана", "floor",
               "признак ML (категория: 1-й и последний дешевле)"],
              ["Тип объекта", "-", "-", "признак ML (категория)"],
              ["Отделка (по корпусу)", "-> Отделка", "finishing",
               "признак ML"],
              ["Ипотека", "пропуски -> НЕТ", "mortgage", "признак ML"],
              ["Переуступка", "пропуски -> Первый владелец", "assignment",
               "ЦЕЛЬ классификации: переуступка да/нет"],
          ])

    p(doc, "Производные колонки, которые создаёт очистка:")
