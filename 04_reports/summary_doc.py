import json
import os
import sys

from docx import Document
from docx.shared import Pt

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config


def h(doc, text, level=1):
    doc.add_heading(text, level=level)


def p(doc, text, bold=False):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    return par


def bullets(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def numbered(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Number")


def table(doc, header, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    for j, htext in enumerate(header):
        t.rows[0].cells[j].text = htext
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            t.rows[i + 1].cells[j].text = str(val)
    return t


def main():
    doc = Document()
    # чуть компактнее шрифт
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)

    # читаем реальные метрики, если есть
    metrics = {}
    mpath = os.path.join(config.OUTPUT_DIR, "metrics.json")
    if os.path.exists(mpath):
        with open(mpath, encoding="utf-8") as f:
            metrics = json.load(f)
    reg = metrics.get("регрессия_предполагаемая_цена", {})
    clf = metrics.get("классификация_переуступки", {})
    fc = metrics.get("прогноз_2026", {})

