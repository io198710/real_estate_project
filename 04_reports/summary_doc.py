        "на ней нельзя, поэтому основной объём цен даёт прайс-лист.",
        "Прайс-лист — цена без скидки; скидка учтена медианным "
        "коэффициентом 0,96, но у отдельных сделок скидка может быть "
        "больше (разброс до +-20%).",
        "Пропуски цены (9%) заполнены общей медианой по рынку — это "
